    {
        $reviews = Review::query();
        if($request->rating){
            $reviews->orderBy('rating', explode(",",$request->rating)[1]);
        }
        $reviews = $reviews->orderBy('created_at', 'desc')->paginate(15);
        return view('shop.backend.product.reviews.index', compact('reviews'));
